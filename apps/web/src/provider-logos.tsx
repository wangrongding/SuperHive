/** 把参与者记录的 provider 归一成已知标识；未知或缺失时返回 undefined，由调用方回退 */
export function providerLogoName(provider: string | undefined): ProviderLogoName | undefined {
  const key = provider?.trim().toLowerCase();
  return key && key in logos ? (key as ProviderLogoName) : undefined;
}

export function ProviderLogo({ provider }: { provider: ProviderLogoName }) {
  const id = useId().replace(/:/g, "");
  const logo = logos[provider];
  return (
    <svg
      className="provider-logo"
      viewBox={logo.viewBox}
      fill={logo.fill}
      fillRule={logo.fillRule}
      aria-hidden="true"
      focusable="false"
    >
      {logo.render(id)}
    </svg>
  );
}
